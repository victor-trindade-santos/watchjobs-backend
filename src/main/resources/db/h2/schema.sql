-- Schema para o perfil h2 (rodar sem Docker e sem instalar banco): .\gradlew.bat bootRun -Ph2
-- Espelha, em SQL compatível com o H2, as 4 tabelas do schema core usadas pela aplicação (V1 + V2 do Flyway).
-- As regras de status e de salário são garantidas pela Bean Validation e pelos services.

CREATE SCHEMA IF NOT EXISTS core;

CREATE TABLE core.users (
    users_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(60) NOT NULL,
    last_name varchar(80) NOT NULL,
    birth_date date NOT NULL,
    email varchar(254) NOT NULL,
    "password" varchar(255) NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_login_at timestamp NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE core.applicationstage (
    application_stage_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" varchar(100) NOT NULL
);

CREATE TABLE core.saved_job (
    saved_job_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id int NOT NULL,
    position_role varchar(255) NOT NULL,
    organization_name varchar(150) NOT NULL,
    job_url text NULL,
    location_city text NULL,
    location_state text NULL,
    location_country_code varchar(2) NULL,
    work_mode varchar(30) NULL,
    experience_level varchar(30) NULL,
    job_type varchar(50) NULL,
    salary_min numeric(10, 2) NULL,
    salary_max numeric(10, 2) NULL,
    salary_currency char(3) NULL,
    status varchar(30) DEFAULT 'SAVED' NOT NULL,
    notes text NULL,
    saved_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status_updated_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_saved_job_users_id FOREIGN KEY (users_id) REFERENCES core.users (users_id)
);

CREATE TABLE core.application (
    application_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_status varchar(20) NOT NULL,
    start_date date NOT NULL,
    end_date date NULL,
    interview_at timestamp NULL,
    notes text NULL,
    feedback text NULL,
    application_stage_id int NOT NULL,
    users_id int NOT NULL,
    saved_job_id bigint NOT NULL,
    CONSTRAINT uq_application_saved_job_id UNIQUE (saved_job_id),
    CONSTRAINT application_saved_job_id_fkey FOREIGN KEY (saved_job_id)
        REFERENCES core.saved_job (saved_job_id) ON DELETE CASCADE,
    CONSTRAINT application_stage_id FOREIGN KEY (application_stage_id)
        REFERENCES core.applicationstage (application_stage_id),
    CONSTRAINT users_id FOREIGN KEY (users_id) REFERENCES core.users (users_id)
);

